/**
 * VoxelSite Visual Editor — Source Address Module (VE-004)
 *
 * Single source of truth for parent-side address handling.
 * Every selectable DOM node in the preview carries `data-vx-*` attributes
 * injected by preview.php. This module normalizes, validates, and compares
 * those addresses so the rest of the editor never does ad-hoc field checks.
 *
 * Normalized shape:
 *   {
 *     sourceFile:   string,        // e.g. "index.php", "_partials/header.php"
 *     sourceKind:   string,        // "page" | "partial" | "component" | "loop" | "unsafe"
 *     nodeKey:      string,        // stable key within the source file
 *     includeChain: string[],      // e.g. ["_partials/header.php", "_partials/nav.php"]
 *     instanceKey:  string,        // unique composite key for this address
 *     editable:     boolean,       // server-side editability flag
 *   }
 */

// ═══════════════════════════════════════════
//  Source kinds — the taxonomy
// ═══════════════════════════════════════════

/**
 * Source kinds that the visual editor fully supports for editing.
 * Everything else is treated as read-only with an escalation message.
 */
const EDITABLE_KINDS = new Set(['page', 'partial', 'component']);

/**
 * Source kinds that indicate the element is global (shared across pages).
 * Edits to these affect every page that includes the partial.
 */
const GLOBAL_KINDS = new Set(['partial', 'component']);

/**
 * Human-readable explanations for read-only source kinds.
 */
const READ_ONLY_MESSAGES = {
  loop:    'Generated by a PHP loop. Use the Code Editor to modify the template.',
  unsafe:  'Contains dynamic PHP. Use the Code Editor for full control.',
};

// ═══════════════════════════════════════════
//  Normalizer
// ═══════════════════════════════════════════

/**
 * Normalize a raw source address (from bridge `data-vx-*` attributes)
 * into the canonical shape. Missing fields get safe defaults.
 *
 * @param {object|null} raw - Raw address object from bridge payload
 * @returns {object} Normalized address
 */
export function normalizeSourceAddress(raw) {
  if (!raw || typeof raw !== 'object') {
    return {
      sourceFile: '',
      sourceKind: 'unsafe',
      nodeKey: '',
      includeChain: [],
      instanceKey: '',
      editable: false,
    };
  }

  const sourceFile = typeof raw.sourceFile === 'string' ? raw.sourceFile : '';
  const sourceKind = typeof raw.sourceKind === 'string' ? raw.sourceKind : 'unsafe';
  const nodeKey = typeof raw.nodeKey === 'string' ? raw.nodeKey : '';
  const editable = raw.editable === true || raw.editable === 'true';

  // includeChain can arrive as comma-separated string or array
  let includeChain = [];
  if (Array.isArray(raw.includeChain)) {
    includeChain = raw.includeChain;
  } else if (typeof raw.includeChain === 'string' && raw.includeChain) {
    includeChain = raw.includeChain.split(',').map(s => s.trim()).filter(Boolean);
  }

  // Build a stable composite key for comparison
  const instanceKey = [sourceFile, sourceKind, nodeKey].filter(Boolean).join('::');

  return {
    sourceFile,
    sourceKind,
    nodeKey,
    includeChain,
    instanceKey,
    editable,
  };
}

// ═══════════════════════════════════════════
//  Comparators
// ═══════════════════════════════════════════

/**
 * Are two normalized addresses pointing to the same source location?
 *
 * @param {object} a - Normalized address
 * @param {object} b - Normalized address
 * @returns {boolean}
 */
export function addressesEqual(a, b) {
  if (!a || !b) return false;
  return a.instanceKey === b.instanceKey;
}

// ═══════════════════════════════════════════
//  Editability
// ═══════════════════════════════════════════

/**
 * Can this address be edited in the visual editor?
 * Returns true for `page`, `partial`, and `component` kinds
 * where the server has also marked the node as editable.
 *
 * @param {object} address - Normalized address
 * @returns {boolean}
 */
export function isEditableAddress(address) {
  if (!address) return false;
  // Both the source kind must be editable AND the server-side flag must agree
  return EDITABLE_KINDS.has(address.sourceKind) && address.editable;
}

/**
 * Get the human-readable read-only explanation for an address,
 * or null if the address is editable.
 *
 * @param {object} address - Normalized address
 * @returns {string|null}
 */
export function getReadOnlyMessage(address) {
  if (!address) return READ_ONLY_MESSAGES.unsafe;
  if (isEditableAddress(address)) return null;
  // Unknown source: instrumentation was unavailable
  if (address.sourceKind === 'unsafe' && !address.sourceFile) {
    return 'Could not determine the source file. Changes cannot be saved safely.';
  }
  return READ_ONLY_MESSAGES[address.sourceKind] || READ_ONLY_MESSAGES.unsafe;
}

/**
 * Is this address from a global (shared) source?
 * Global elements live in partials/components that are included on multiple pages.
 * Edits propagate to every page that includes the partial.
 *
 * @param {object} address - Normalized address
 * @returns {boolean}
 */
export function isGlobalAddress(address) {
  if (!address) return false;
  return GLOBAL_KINDS.has(address.sourceKind);
}
